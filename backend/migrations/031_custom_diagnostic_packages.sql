-- Patient-built diagnostic packages and a reusable test catalogue.

CREATE TABLE IF NOT EXISTS diagnostic_tests (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  source_number INTEGER UNIQUE NOT NULL,
  slug TEXT UNIQUE NOT NULL,
  name TEXT NOT NULL,
  aliases TEXT[] NOT NULL DEFAULT '{}',
  category TEXT NOT NULL,
  price NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (price >= 0),
  price_confirmed BOOLEAN NOT NULL DEFAULT false,
  preparation_instructions TEXT,
  sample_type TEXT,
  report_turnaround TEXT,
  requires_clinic_confirmation BOOLEAN NOT NULL DEFAULT false,
  is_active BOOLEAN NOT NULL DEFAULT true,
  display_order INTEGER NOT NULL DEFAULT 0,
  version INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE package_orders
  ADD COLUMN IF NOT EXISTS order_type TEXT NOT NULL DEFAULT 'health_package',
  ADD COLUMN IF NOT EXISTS clinical_notes TEXT,
  ADD COLUMN IF NOT EXISTS price_status TEXT NOT NULL DEFAULT 'confirmed',
  ADD COLUMN IF NOT EXISTS consent_given_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS request_idempotency_key TEXT;

CREATE TABLE IF NOT EXISTS custom_test_order_items (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id UUID NOT NULL REFERENCES package_orders(id) ON DELETE CASCADE,
  diagnostic_test_id UUID NOT NULL REFERENCES diagnostic_tests(id) ON DELETE RESTRICT,
  patient_id UUID NOT NULL REFERENCES patients(id) ON DELETE RESTRICT,
  test_name_snapshot TEXT NOT NULL,
  category_snapshot TEXT NOT NULL,
  unit_price NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (unit_price >= 0),
  price_confirmed_snapshot BOOLEAN NOT NULL DEFAULT false,
  preparation_snapshot TEXT,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (order_id, diagnostic_test_id, patient_id)
);

CREATE INDEX IF NOT EXISTS idx_diagnostic_tests_public_catalog
  ON diagnostic_tests(is_active, category, display_order);
CREATE INDEX IF NOT EXISTS idx_custom_test_order_items_order
  ON custom_test_order_items(order_id, sort_order);
CREATE INDEX IF NOT EXISTS idx_package_orders_order_type
  ON package_orders(order_type, created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS idx_package_orders_request_idempotency
  ON package_orders(request_idempotency_key)
  WHERE request_idempotency_key IS NOT NULL;

